// Exports the PUBLIC, approved YouTube videos for the iScream Studio "See it in action" area as JSON (stdout). A video is included only if the Studio
// records it as approved and public AND YouTube itself reports it public right now; an unlisted or review video is never exported. Read-only.
//   runuser -u gbstudio -- tsx --env-file=/etc/gravyblock-marketing.env scripts/ops/marketing-export-portfolio.ts > product-videos.json
import { closeStudioDb, requireStudioDb } from "../../src/lib/marketing-studio/db";
import { angleKey, type AngleEntry } from "../../src/lib/marketing-studio/library";
import { PLAN_PRODUCTS } from "../../src/lib/marketing-studio/library-plan";
import { youtubeTokensForCall } from "../../src/lib/marketing-studio/publishing/oauth-youtube";
import { embedFor } from "../../src/lib/marketing-studio/publishing/video-review";
import { fetchYoutubeLiveMetadata } from "../../src/lib/marketing-studio/publishing/youtube-api";
import { youtubeConnectionFor } from "../../src/lib/marketing-studio/publishing/youtube-share";
import { listProducts } from "../../src/lib/marketing-studio/repository";
import { getSetting } from "../../src/lib/marketing-studio/runtime";
import { INTERNAL_SCOPE } from "../../src/lib/marketing-studio/scope";

async function main() {
  const db = requireStudioDb();
  const products = await listProducts(INTERNAL_SCOPE, db);
  const out: Array<Record<string, unknown>> = [];
  for (const p of PLAN_PRODUCTS) {
    const entries = await getSetting<AngleEntry[]>(angleKey(p.slug), [], db);
    const candidates = entries.filter((e) => e.status === "public" && e.youtubeId);
    if (!candidates.length) continue;
    const sp = products.find((x) => x.slug === p.slug);
    const conn = sp ? await youtubeConnectionFor(db, sp.id) : null;
    if (!conn) continue;
    const t = await youtubeTokensForCall(INTERNAL_SCOPE, "portfolio-export", conn.productId, conn.id, { fetch }, db);
    const videos: Array<Record<string, unknown>> = [];
    for (const e of candidates) {
      let live = await fetchYoutubeLiveMetadata({ videoId: e.youtubeId!, accessToken: t.accessToken }, { fetch });
      // YouTube can briefly report a stale value right after a change: ask a few times and require a consistent answer
      for (let i = 0; i < 2 && live.privacy !== "public"; i++) {
        await new Promise((r) => setTimeout(r, 4000));
        live = await fetchYoutubeLiveMetadata({ videoId: e.youtubeId!, accessToken: t.accessToken }, { fetch });
      }
      if (live.privacy !== "public") continue;
      videos.push({ title: live.title ?? e.title, demonstrates: e.goal, youtubeId: e.youtubeId, embedUrl: embedFor(e.youtubeId!, e.title).embedUrl, thumbnailUrl: `https://i.ytimg.com/vi/${e.youtubeId}/hqdefault.jpg` });
    }
    if (videos.length) out.push({ name: p.name, host: p.host, visitUrl: p.home, videos });
  }
  console.log(JSON.stringify({ generatedAt: new Date().toISOString(), note: "Public, approved YouTube videos only. Generated by Marketing Studio; the site code that reads it is separate.", products: out }, null, 2));
}

main().catch((e) => { console.error(e instanceof Error ? e.message : e); process.exitCode = 1; }).finally(() => closeStudioDb());
