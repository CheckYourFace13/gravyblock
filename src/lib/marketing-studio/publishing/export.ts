/**
 * Export bundles: everything an operator needs to post manually where direct publishing is not available or not approved. A small
 * dependency-free ZIP writer (stored, no compression) keeps this free of new packages. The bundle holds the media, caption, CTA,
 * platform notes and a manifest, with a safe file name and the recommended aspect ratio.
 */
import { promises as fs } from "node:fs";
import { STUDIO_DIRS } from "../config";
import { safeJoin } from "../storage";
import { aspectLabel, specFor } from "./platforms";

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

export function crc32(buf: Uint8Array): number {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/** Writes a valid ZIP archive using the "stored" method. File names must already be safe (letters, digits, dot, dash, underscore). */
export function zipStore(files: Array<{ name: string; data: Buffer }>): Buffer {
  const locals: Buffer[] = [];
  const centrals: Buffer[] = [];
  let offset = 0;
  const date = 0x5a21; // 2025-01-01
  for (const f of files) {
    if (!/^[A-Za-z0-9._-]+$/.test(f.name)) throw new Error(`unsafe file name in bundle: ${f.name}`);
    const name = Buffer.from(f.name, "utf8");
    const crc = crc32(f.data);
    const lh = Buffer.alloc(30);
    lh.writeUInt32LE(0x04034b50, 0);
    lh.writeUInt16LE(20, 4);
    lh.writeUInt16LE(0x0800, 6); // UTF-8 names
    lh.writeUInt16LE(0, 8);
    lh.writeUInt16LE(0, 10);
    lh.writeUInt16LE(date, 12);
    lh.writeUInt32LE(crc, 14);
    lh.writeUInt32LE(f.data.length, 18);
    lh.writeUInt32LE(f.data.length, 22);
    lh.writeUInt16LE(name.length, 26);
    lh.writeUInt16LE(0, 28);
    locals.push(lh, name, f.data);
    const ch = Buffer.alloc(46);
    ch.writeUInt32LE(0x02014b50, 0);
    ch.writeUInt16LE(20, 4);
    ch.writeUInt16LE(20, 6);
    ch.writeUInt16LE(0x0800, 8);
    ch.writeUInt16LE(0, 10);
    ch.writeUInt16LE(0, 12);
    ch.writeUInt16LE(date, 14);
    ch.writeUInt32LE(crc, 16);
    ch.writeUInt32LE(f.data.length, 20);
    ch.writeUInt32LE(f.data.length, 24);
    ch.writeUInt16LE(name.length, 28);
    ch.writeUInt32LE(offset, 42);
    centrals.push(ch, name);
    offset += 30 + name.length + f.data.length;
  }
  const centralBuf = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(files.length, 8);
  end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(centralBuf.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, centralBuf, end]);
}

export type ExportInput = {
  productName: string;
  productSlug: string;
  publicationId: string;
  platform: string;
  mode: string;
  media: { storagePath: string; mime: string; kind: "image" | "video"; width: number; height: number; durationSec?: number | null };
  caption: string;
  title?: string | null;
  ctaText?: string | null;
  ctaUrl?: string | null;
  scheduledFor?: Date | null;
};

const safeName = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 40) || "item";

export async function buildExportBundle(i: ExportInput): Promise<{ fileName: string; zip: Buffer; manifest: Record<string, unknown> }> {
  const spec = specFor(i.platform);
  if (!spec) throw new Error("Unknown platform");
  const ext = i.media.mime === "video/mp4" ? "mp4" : i.media.mime === "image/jpeg" ? "jpg" : "png";
  const aspect = aspectLabel(i.media.width, i.media.height).replace(":", "x");
  const base = `${safeName(i.productSlug)}-${i.platform}-${aspect}-${i.publicationId.slice(0, 8)}`;
  const mediaBytes = await fs.readFile(safeJoin(STUDIO_DIRS.media, ...i.media.storagePath.split("/")));
  const recommended = (i.media.kind === "image" ? spec.media.image : spec.media.video)?.aspects.map((a) => a.label).join(" or ") ?? "n/a";
  const notes = [
    `${spec.label}: manual upload instructions`,
    "",
    `Product: ${i.productName}`,
    `File: ${base}.${ext} (${i.media.kind}, ${i.media.width}x${i.media.height}${i.media.durationSec ? `, ${i.media.durationSec.toFixed(1)}s` : ""})`,
    `Recommended aspect ratio: ${recommended}`,
    i.scheduledFor ? `Planned time: ${i.scheduledFor.toISOString()}` : "No planned time set",
    "",
    ...spec.exportNotes,
    "",
    "Why this is an export: " + (spec.direct === "available_with_healthy_connection" ? "no connected account was used for this item." : spec.approvalNote),
    "",
    "Still to verify on the platform: " + spec.verify.join("; "),
    "",
    "Generated by GravyBlock Marketing Studio. Nothing was posted by Marketing Studio.",
  ].join("\n");
  const manifest = { publicationId: i.publicationId, platform: i.platform, mode: i.mode, mediaFile: `${base}.${ext}`, width: i.media.width, height: i.media.height, durationSec: i.media.durationSec ?? null, title: i.title ?? null, ctaText: i.ctaText ?? null, ctaUrl: i.ctaUrl ?? null, recommendedAspect: recommended };
  const files = [
    { name: `${base}.${ext}`, data: mediaBytes },
    { name: "caption.txt", data: Buffer.from(i.caption + "\n", "utf8") },
    ...(i.title ? [{ name: "title.txt", data: Buffer.from(i.title + "\n", "utf8") }] : []),
    ...(i.ctaText || i.ctaUrl ? [{ name: "cta.txt", data: Buffer.from(`${i.ctaText ?? ""}\n${i.ctaUrl ?? ""}\n`, "utf8") }] : []),
    { name: `notes-${i.platform}.txt`, data: Buffer.from(notes, "utf8") },
    { name: "manifest.json", data: Buffer.from(JSON.stringify(manifest, null, 2), "utf8") },
  ];
  return { fileName: `${base}.zip`, zip: zipStore(files), manifest };
}

