// ---- text ---------------------------------------------------------------------------------------------------------------------

/** Splits a spoken line into words and `{marker}` anchors. A marker points at the word that follows it. */
export function parseSpoken(spoken: string): { words: string[]; markers: Record<string, number> } {
  const words: string[] = [];
  const markers: Record<string, number> = {};
  for (const tok of spoken.trim().split(/\s+/)) {
    const m = /^\{([a-z0-9_-]+)\}(.*)$/i.exec(tok);
    if (m) {
      markers[m[1]] = words.length;
      if (m[2]) words.push(m[2]);
    } else words.push(tok);
  }
  return { words, markers };
}

/** Relative time each word takes: longer words take longer and punctuation adds a small pause. Applied inside the measured audio length. */
function weights(words: string[]): number[] {
  return words.map((w, i) => {
    const letters = w.replace(/[^A-Za-z0-9]/g, "").length;
    const pause = i === words.length - 1 ? 0 : /[.?!]$/.test(w) ? 5 : /[,;:]$/.test(w) ? 3 : 0;
    return letters + 1.6 + pause;
  });
}

/** Word times (ms from the start of the voiced audio) for display words, spread over the real duration of the audio. */
export function wordTimings(words: string[], durMs: number): WordTime[] {
  const w = weights(words);
  const total = w.reduce((a, b) => a + b, 0) || 1;
  let acc = 0;
  return words.map((text, i) => {
    const from = (acc / total) * durMs;
    acc += w[i];
    return { text, from, to: (acc / total) * durMs };
  });
}

export function captionWordsFor(line: Pick<NarrationLine, "spoken" | "caption">): string[] {
  return line.caption ? line.caption.trim().split(/\s+/) : parseSpoken(line.spoken).words;
}

/** Caption groups of at most three words that break at punctuation, each timed from its words. */
export function groupCaptions(words: WordTime[], offsetMs: number): Array<{ from: number; to: number; words: WordTime[] }> {
  const groups: WordTime[][] = [];
  let cur: WordTime[] = [];
  for (const w of words) {
    cur.push(w);
    if (cur.length >= 3 || /[.?!,;:]$/.test(w.text)) {
      groups.push(cur);
      cur = [];
    }
  }
  if (cur.length) {
    // never leave a lone short word dangling at the end
    if (cur.length === 1 && groups.length && groups[groups.length - 1].length < 3) groups[groups.length - 1].push(...cur);
    else groups.push(cur);
  }
  return groups.map((g, i) => {
    const shifted = g.map((w) => ({ text: w.text, from: w.from + offsetMs, to: w.to + offsetMs }));
    const next = groups[i + 1]?.[0];
    return { from: shifted[0].from, to: next ? next.from + offsetMs - 20 : shifted[shifted.length - 1].to + 250, words: shifted };
  });
}

// ---- WAV helpers -----------------------------------------------------------------------------------------------------------------

export function writeWav(file: string, channels: Float32Array[], rate: number): Promise<void> {
  const n = channels[0].length;
  const nc = channels.length;
  const buf = Buffer.alloc(44 + n * nc * 2);
  buf.write("RIFF", 0);
  buf.writeUInt32LE(36 + n * nc * 2, 4);
  buf.write("WAVEfmt ", 8);
  buf.writeUInt32LE(16, 16);
  buf.writeUInt16LE(1, 20);
  buf.writeUInt16LE(nc, 22);
  buf.writeUInt32LE(rate, 24);
  buf.writeUInt32LE(rate * nc * 2, 28);
  buf.writeUInt16LE(nc * 2, 32);
  buf.writeUInt16LE(16, 34);
  buf.write("data", 36);
  buf.writeUInt32LE(n * nc * 2, 40);
  let o = 44;
  for (let i = 0; i < n; i++) for (let c = 0; c < nc; c++) {
    const v = Math.max(-1, Math.min(1, channels[c][i]));
    buf.writeInt16LE(Math.round(v * 32767), o);
    o += 2;
  }
  return fs.writeFile(file, buf);
}

/** Trims leading and trailing near-silence so timing starts and ends on the voice. */
export function trimSilence(samples: Float32Array, rate: number, threshold = 0.012): Float32Array {
  const win = Math.round(rate * 0.01);
  const rms = (s: number) => {
    let a = 0;
    const e = Math.min(samples.length, s + win);
    for (let i = s; i < e; i++) a += samples[i] * samples[i];
    return Math.sqrt(a / Math.max(1, e - s));
  };
  let start = 0;
  while (start < samples.length - win && rms(start) < threshold) start += win;
  let end = samples.length;
  while (end > start + win && rms(end - win) < threshold) end -= win;
  const pad = Math.round(rate * 0.04);
  return samples.slice(Math.max(0, start - pad), Math.min(samples.length, end + pad));
}

/** Evens out loudness between lines: scales to a common RMS, capped so peaks stay clean. */
export function levelLine(samples: Float32Array, targetRms = 0.1): Float32Array {
  let a = 0;
  let peak = 0;
  for (const v of samples) {
    a += v * v;
    peak = Math.max(peak, Math.abs(v));
  }
  const rms = Math.sqrt(a / Math.max(1, samples.length)) || 1;
  const g = Math.min(targetRms / rms, 0.89 / (peak || 1));
  return samples.map((v) => v * g);
}

// ---- voiceover -------------------------------------------------------------------------------------------------------------------

export type SynthLine = { id: string; samples: Float32Array; rate: number };

/** Runs Kokoro from its isolated install folder. Throws a clear message when the voice is not installed. */
export async function synthesizeLines(lines: Array<{ id: string; text: string }>, opts: { ttsDir: string; voice: string; speed: number }): Promise<SynthLine[]> {
  const entry = path.join(opts.ttsDir, "node_modules", "kokoro-js", "dist", "kokoro.js");
  try {
    await fs.access(entry);
  } catch {
    throw new Error(`The voiceover engine is not installed (expected ${entry}). Install kokoro-js into that folder first.`);
  }
  const mod = (await import(pathToFileURL(entry).href)) as { KokoroTTS: { from_pretrained: (id: string, o: Record<string, unknown>) => Promise<{ generate: (t: string, o: Record<string, unknown>) => Promise<{ audio: Float32Array; sampling_rate: number }> }> } };
  const tts = await mod.KokoroTTS.from_pretrained("onnx-community/Kokoro-82M-v1.0-ONNX", { dtype: "q8", device: "cpu" });
  const out: SynthLine[] = [];
  for (const l of lines) {
    const a = await tts.generate(l.text, { voice: opts.voice, speed: opts.speed });
    out.push({ id: l.id, samples: levelLine(trimSilence(a.audio, a.sampling_rate), 0.1), rate: a.sampling_rate });
  }
  return out;
}

/** Places each line on one mono track at its start time. */
export function placeLines(lines: Array<{ samples: Float32Array; rate: number; startMs: number }>, totalMs: number, rate: number): Float32Array {
  const track = new Float32Array(Math.ceil((totalMs / 1000) * rate));
  for (const l of lines) {
    const s = l.rate === rate ? l.samples : resample(l.samples, l.rate, rate);
    const at = Math.round((l.startMs / 1000) * rate);
    for (let i = 0; i < s.length && at + i < track.length; i++) track[at + i] += s[i];
  }
  return track;
}

function resample(s: Float32Array, from: number, to: number): Float32Array {
  const n = Math.round((s.length * to) / from);
  const out = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    const x = (i * from) / to;
    const i0 = Math.floor(x);
    const f = x - i0;
    out[i] = (s[i0] ?? 0) * (1 - f) + (s[i0 + 1] ?? s[i0] ?? 0) * f;
  }
  return out;
}

