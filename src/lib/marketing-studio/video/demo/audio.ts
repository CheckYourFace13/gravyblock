/** Voiceover on top, music ducked under it, then loudness-normalised for social platforms (about -15 LUFS integrated). */
export async function mixAudio(voWav: string, musicWav: string, outWav: string, durationSec: number): Promise<void> {
  const fadeOutStart = Math.max(0, durationSec - 1.8);
  const filter = [
    "[0:a]pan=stereo|c0=c0|c1=c0,asplit=2[vo][vosc]",
    `[1:a]volume=0.55,afade=t=in:d=0.8,afade=t=out:st=${fadeOutStart.toFixed(2)}:d=1.8[m]`,
    "[m][vosc]sidechaincompress=threshold=0.02:ratio=10:attack=8:release=420:makeup=1[md]",
    "[vo][md]amix=inputs=2:normalize=0:duration=longest[mix]",
    "[mix]loudnorm=I=-15:TP=-1.5:LRA=9[out]",
  ].join(";");
  const r = await ffmpeg(["-i", voWav, "-i", musicWav, "-filter_complex", filter, "-map", "[out]", "-ar", "48000", "-ac", "2", outWav], 120_000);
  if (r.code !== 0) throw new Error(`audio mix failed: ${r.stderr.slice(0, 300)}`);
}

export function audioInfo(voice: string, speed: number): DemoAudioInfo {
  return { voiceover: { ...VOICE, voice, speed }, music: { ...MUSIC } };
}
