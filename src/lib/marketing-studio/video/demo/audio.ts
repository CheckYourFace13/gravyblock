/** A simple, upbeat original loop: bass, soft pads, a plucked arpeggio and light drums. Deterministic. */
export function synthMusic(durationSec: number, rate = 44100): [Float32Array, Float32Array] {
  const n = Math.ceil(durationSec * rate);
  const L = new Float32Array(n);
  const R = new Float32Array(n);
  const bpm = 112;
  const beat = 60 / bpm;
  const bar = beat * 4;
  // Am - F - C - G, one chord per bar (MIDI roots and triads)
  const chords: Array<{ root: number; notes: number[] }> = [
    { root: 45, notes: [57, 60, 64] },
    { root: 41, notes: [53, 57, 60] },
    { root: 48, notes: [60, 64, 67] },
    { root: 43, notes: [55, 59, 62] },
  ];
  const hz = (m: number) => 440 * Math.pow(2, (m - 69) / 12);
  let seed = 1337;
  const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296) * 2 - 1;
  const add = (t0: number, dur: number, fn: (t: number) => number, pan = 0, gain = 1) => {
    const s = Math.max(0, Math.floor(t0 * rate));
    const e = Math.min(n, Math.floor((t0 + dur) * rate));
    const gl = gain * (pan <= 0 ? 1 : 1 - pan);
    const gr = gain * (pan >= 0 ? 1 : 1 + pan);
    for (let i = s; i < e; i++) {
      const v = fn((i - s) / rate);
      L[i] += v * gl;
      R[i] += v * gr;
    }
  };
  const bars = Math.ceil(durationSec / bar);
  for (let b = 0; b < bars; b++) {
    const c = chords[b % chords.length];
    const t = b * bar;
    // bass: root on beats 1 and 3 with a lift
    for (const [bt, note] of [[0, c.root], [1.5, c.root], [2, c.root + 7], [3.5, c.root + 12]] as Array<[number, number]>)
      add(t + bt * beat, beat * 0.9, (x) => (Math.sin(2 * Math.PI * hz(note) * x) * 0.7 + Math.sin(4 * Math.PI * hz(note) * x) * 0.15) * Math.exp(-x * 3.2) * Math.min(1, x * 200), 0, 0.5);
    // pad: soft triad across the bar
    for (const note of c.notes) for (const det of [-0.12, 0.12])
      add(t, bar + 0.1, (x) => Math.sin(2 * Math.PI * hz(note + det) * x) * Math.min(1, x * 3) * Math.min(1, (bar + 0.1 - x) * 4) * 0.5, det * 4, 0.1);
    // pluck arpeggio on eighth notes
    for (let k = 0; k < 8; k++) {
      const note = c.notes[[0, 1, 2, 1, 2, 1, 0, 1][k] % 3] + 12;
      add(t + k * beat * 0.5, beat * 0.7, (x) => (Math.sin(2 * Math.PI * hz(note) * x) * 0.6 + Math.sin(2 * Math.PI * hz(note) * 2 * x) * 0.25) * Math.exp(-x * 9), (k % 2 ? 0.35 : -0.35), 0.16);
    }
    // drums: kick on 1 and 3, snare on 2 and 4, hats on eighths
    for (const bt of [0, 2]) add(t + bt * beat, 0.22, (x) => Math.sin(2 * Math.PI * (45 + 90 * Math.exp(-x * 28)) * x) * Math.exp(-x * 11), 0, 0.85);
    for (const bt of [1, 3]) add(t + bt * beat, 0.16, (x) => rnd() * Math.exp(-x * 22) * 0.55 + Math.sin(2 * Math.PI * 190 * x) * Math.exp(-x * 20) * 0.35, 0, 0.32);
    for (let k = 0; k < 8; k++) add(t + k * beat * 0.5, 0.05, (x) => rnd() * Math.exp(-x * 90), k % 2 ? 0.25 : -0.25, 0.1);
  }
  // soft limiter and master fades
  for (let i = 0; i < n; i++) {
    const tt = i / rate;
    const fade = Math.min(1, tt / 1.0) * Math.min(1, (durationSec - tt) / 1.8);
    L[i] = Math.tanh(L[i] * 0.9) * 0.8 * fade;
    R[i] = Math.tanh(R[i] * 0.9) * 0.8 * fade;
  }
  return [L, R];
}

